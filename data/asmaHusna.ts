// Deterministic "name of the day" so every user sees the same name on a given date.
export function nameOfTheDayIndex(total: number = asmaHusna.length): number {
  const today = new Date();
  const dayOfYear = Math.floor(
    (Date.UTC(today.getFullYear(), today.getMonth(), today.getDate()) - Date.UTC(today.getFullYear(), 0, 0)) / 86400000,
  );
  return total > 0 ? dayOfYear % total : 0;
}
